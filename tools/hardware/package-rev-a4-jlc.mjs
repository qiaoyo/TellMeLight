import { createHash } from 'node:crypto';
import {
  copyFile,
  mkdir,
  readdir,
  readFile,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import { basename, join, relative } from 'node:path';
import { spawnSync } from 'node:child_process';

const repoRoot = process.cwd();
const outputsDir = join(repoRoot, 'hardware', 'outputs', 'rev_a4');
const packageDir = join(outputsDir, 'jlc_upload');

function posixPath(path) {
  return path.split('\\').join('/');
}

function psQuote(path) {
  return `'${path.replaceAll("'", "''")}'`;
}

async function walkFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await walkFiles(path));
    } else if (entry.isFile()) {
      files.push(path);
    }
  }
  return files.sort();
}

async function hashFile(path) {
  const bytes = await readFile(path);
  return createHash('sha256').update(bytes).digest('hex');
}

async function copyTracked(files, manifestFiles) {
  for (const file of files) {
    await mkdir(join(packageDir, file.toDir), { recursive: true });
    const target = join(packageDir, file.toDir, file.targetName ?? basename(file.source));
    await copyFile(file.source, target);
    const info = await stat(target);
    manifestFiles.push({
      path: posixPath(relative(packageDir, target)),
      source: posixPath(relative(repoRoot, file.source)),
      bytes: info.size,
      sha256: await hashFile(target),
    });
  }
}

function compressArchive(literalPaths, destination) {
  const literalList = literalPaths.map(psQuote).join(',');
  const command = `Compress-Archive -LiteralPath ${literalList} -DestinationPath ${psQuote(destination)} -Force`;
  const result = spawnSync('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', command], {
    cwd: repoRoot,
    encoding: 'utf8',
  });

  if (result.error) {
    throw result.error;
  }

  if (result.status !== 0) {
    throw new Error(`Compress-Archive failed for ${destination}\n${result.stderr || result.stdout}`);
  }
}

async function addPackageFileToManifest(path, manifestFiles) {
  const info = await stat(path);
  manifestFiles.push({
    path: posixPath(relative(packageDir, path)),
    source: 'generated by tools/hardware/package-rev-a4-jlc.mjs',
    bytes: info.size,
    sha256: await hashFile(path),
  });
}

